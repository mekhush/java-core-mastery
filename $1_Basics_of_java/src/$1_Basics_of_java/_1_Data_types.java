package $1_Basics_of_java;

public class _1_Data_types {
	
	public static void main(String[] args) {
		boolean b = false;
		char c = 'k';
		int n = 22;
		short s = 12345;
		long l = 1223334444;
		float f = 1.122333444455555f;
		double d = 15.122333444455555d;
		
		
		System.out.println("The default value of the boolean is --"+b+"-- and the size in windows is 1 bit and size in mac/linux is 2 bit");
		System.out.println("The character initialized value is --"+c+"-- and the size in 2 bytes");
		System.out.println("The Integer initialized value is --"+n+"-- and the size in 4 bytes");
		System.out.println("The Short initialized value is --"+s+"-- and the size in 2 bytes");
		System.out.println("The long initialized value is --"+l+"-- and the size in 8 bytes");
		System.out.println("The float initialized value is --"+f+"-- and the size in 4 bytes");
		System.out.println("The Double initialized value is --"+d+"-- and the size in 8 bytes");
		
		}

}
